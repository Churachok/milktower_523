export function personalizedNews(applications) {
  const rows = [...applications].sort((a, b) => Date.parse(b.updatedAt) - Date.parse(a.updatedAt));
  const recent = rows[0];
  const selected = [];
  const add = (id, reason, route) => {
    if (!selected.some((item) => item.id === id))
      selected.push({ ...ARTICLES[id], reason, route: route || ARTICLES[id].route });
  };
  const request = rows.find((a) => a.status === "needs_info");
  const offer = rows.find((a) => a.status === "approved");
  if (request) add("clarification", `По заявке ${request.id} нужны сведения`, `/applications/${request.id}`);
  if (offer) add("offers", `Для вас подготовлено предложение ${offer.id}`, `/applications/${offer.id}`);
  if (recent?.productId === "equipment") add("equipment", "Вы рассматриваете финансирование оборудования");
  if (recent?.productId === "working") add("working", "Ваша последняя заявка — на оборотные средства");
  if (/услуг|IT|технолог/i.test(recent?.company?.industry || "")) add("services", "По сфере деятельности вашей компании");
  const f = recent?.finances;
  if (f && Number(f.revenue) > 0 && (Number(f.debt) > 0 || Number(f.expenses) / Number(f.revenue) > 0.7))
    add("resilience", "По указанным расходам и обязательствам полезно проверить запас бюджета");
  if (!recent || rows.some((a) => a.status === "draft")) add("documents", "Для подготовки новой заявки");
  add("resilience", "Для планирования платежей по кредиту");
  add("offers", "Обновление возможностей вашего кабинета");
  return selected.slice(0, 5);
}
